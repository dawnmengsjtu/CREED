"""Pre-registered Stage A analysis (PLAN.md section 6). usage: python analyze.py OUT_ROOT"""
import json
import sys

import numpy as np
from scipy.stats import spearmanr, t as tdist

OUT = sys.argv[1]
XL = '/public/home/mengxl/creed-research-runs/crosslayer-matrix-20261009-0001/output'
SCEN = ('new_cell', 'tissue')
YS = ('RNA', 'P')
RS = (4, 8, 16, 32, 64)
PAIRS = (('M', 'RNA'), ('M', 'P'), ('RNA', 'P'), ('RNA', 'M'), ('P', 'M'), ('P', 'RNA'))
MEAS = {frozenset(('M', 'RNA')): 'M+RNA', frozenset(('M', 'P')): 'M+P', frozenset(('RNA', 'P')): 'RNA+P'}


def nb_t(d, n_train, n_test):
    """Nadeau-Bengio corrected resampled t over folds (one-sided p for mean > 0)."""
    d = np.asarray(d, float); k = len(d)
    v = d.var(ddof=1) * (1 / k + n_test / n_train)
    if v <= 0:
        return float('nan'), float('nan')
    t = d.mean() / np.sqrt(v)
    return float(t), float(1 - tdist.cdf(t, k - 1))


def load(scen):
    R = [json.load(open(f'{OUT}/{scen}/fold-{f}/fold_result.json')) for f in range(5)]
    S = {}
    for res in R:
        for row in res['rows']:
            S.setdefault(row['arm'], []).append(row['score'])
    return R, {a: np.array(v) for a, v in S.items()}


def rel(base, arm):
    return (base - arm) / base * 100


report = {'scenarios': {}}
md = ['# Stage A result (auto-generated by analyze.py; numbers only, no interpretation)', '']
for scen in SCEN:
    R, S = load(scen)
    rsel = {y: [r['r_selected'][y] for r in R] for y in YS}
    nfit = np.mean([r['bank_info']['outer']['n_fit'] for r in R]); nq = np.mean([r['bank_info']['outer']['n_query'] for r in R])
    out = {'reproduction_passed': all(r['reproduction_passed'] for r in R),
           'reproduction_max': max(max(r['reproduction'].values()) for r in R), 'r_selected': rsel, 'Y': {}}
    md += [f'## {scen}', '', f"reproduction passed: {out['reproduction_passed']} (max abs diff {out['reproduction_max']:.2e}); "
           f"fold-averaged M = {S['M'].mean():.6f}, H086 RNA = {S['H086_RNA'].mean():.6f}, H086 P = {S['H086_P'].mean():.6f}", '']
    for y in YS:
        star = lambda a: np.array([S[f'{a}_{y}_r{rsel[y][f]}'][f] for f in range(5)])
        starmean = lambda a: np.array([np.mean([S[f'{a}_{y}_r{rsel[y][f]}_s{s}'][f] for s in range(5)]) for f in range(5)])
        arms = {'M': S['M'], 'H086': S[f'H086_{y}'], 'A1*': star('A1'), 'A2': S[f'A2_{y}'], 'A3*': star('A3'),
                'A4*mean': starmean('A4'), 'A5*mean': starmean('A5'), 'A6*': star('A6'), 'A7*': star('A7'),
                'T512': S[f'T512_{y}'], 'CREED_M+Y': S[f'CREED_M+{y}']}
        for r in RS:
            arms[f'A1_r{r}'] = S[f'A1_{y}_r{r}']; arms[f'A6_r{r}'] = S[f'A6_{y}_r{r}']
        room = rel(arms['M'], arms['CREED_M+Y'])
        tab = {}
        for a, v in arms.items():
            d_h = rel(arms['H086'], v); d_m = rel(arms['M'], v)
            t, p = nb_t(d_h, nfit, nq)
            tab[a] = dict(score=float(v.mean()), fold_scores=v.tolist(), d_vs_H086=float(d_h.mean()), d_vs_H086_folds=d_h.tolist(),
                          wins_vs_H086=int((d_h > 0).sum()), d_vs_M=float(d_m.mean()), wins_vs_M=int((d_m > 0).sum()),
                          share=float(d_m.mean() / room.mean()), nb_t_vs_H086=t, nb_p_vs_H086=p)
        a1 = arms['A1*']
        beats = {c: int((a1 < arms[c]).sum()) for c in ('A3*', 'A4*mean', 'A5*mean', 'H086', 'A2')}
        g_a1 = rel(arms['M'], a1).mean(); g_a7 = rel(arms['M'], arms['A7*']).mean()
        out['Y'][y] = dict(room=float(room.mean()), arms=tab, a1_beats_folds=beats, a7_over_a1_gain=float(g_a7 / g_a1) if g_a1 != 0 else float('nan'),
                           a2_minus_a1=float(tab['A2']['d_vs_H086'] - tab['A1*']['d_vs_H086']))
        md += [f'### {y} (room {room.mean():.3f}%, r* by fold {rsel[y]})', '',
               '| arm | sRMSE | Δ vs H086 % | wins vs H086 | Δ vs M % | share | NB p vs H086 |', '|---|---|---|---|---|---|---|']
        for a, v in tab.items():
            md.append(f"| {a} | {v['score']:.6f} | {v['d_vs_H086']:+.3f} | {v['wins_vs_H086']}/5 | {v['d_vs_M']:+.3f} | {v['share']:.3f} | {v['nb_p_vs_H086']:.3f} |")
        md += ['', f"A1* beats (folds of 5): {beats}; A7 gain / A1 gain = {out['Y'][y]['a7_over_a1_gain']:.3f}; "
               f"Δ(A2) − Δ(A1*) = {out['Y'][y]['a2_minus_a1']:+.3f} pp", '']
    # diagnostics: FR2 vs R2 vs share (outer banks, fold-averaged)
    P = {}
    for f in range(5):
        Z = np.load(f'{XL}/{scen}/fold-{f}_predictions.npz', allow_pickle=False)
        truth, sd, use = Z['truth'], Z['train_sd'], Z['evaluated']
        def sc(a):
            e = ((Z['pred__' + a] - truth) / sd) ** 2; o = np.isfinite(truth)
            mse = np.where(o, e, 0).sum(0) / np.maximum(o.sum(0), 1)
            return float(np.sqrt(mse[use].mean()))
        for x, yy in PAIRS:
            meas = MEAS[frozenset((x, yy))]
            P.setdefault(f'{x}->{yy}', []).append((sc(x), sc(f'{x}+v{yy}'), sc(meas)))
    diag = {}
    for x, yy in PAIRS:
        key = f'{x}->{yy}'
        arr = np.array(P[key])
        room = rel(arr[:, 0], arr[:, 2]); gain = rel(arr[:, 0], arr[:, 1])
        dg = [r['bank_info']['outer']['diag'][key if key in r['bank_info']['outer']['diag'] else yy] for r in R]
        diag[key] = dict(room=float(room.mean()), share=float(gain.mean() / room.mean()) if room.mean() != 0 else float('nan'),
                         fr2_oof=float(np.mean([d['fr2_oof'] for d in dg])), r2_oof=float(np.mean([d['r2_mean_oof'] for d in dg])),
                         fr2_query=float(np.mean([d['fr2_query'] for d in dg])), r2_query=float(np.mean([d['r2_mean_query'] for d in dg])))
    for y in YS:
        dg = [r['bank_info']['outer']['diag'][y] for r in R]
        diag[f'M->{y}'].update(splithalf_cos2_at_rstar=float(np.mean([d['splithalf_cos2'][str(rsel[y][f])] for f, d in enumerate(dg)])),
                               fr2_oof_perm_mean=float(np.mean([np.mean(d['fr2_oof_perm']) for d in dg])),
                               ev_frac_top=np.mean([d['ev_frac_top'] for d in dg], axis=0).tolist())
    out['diag'] = diag
    md += ['### Diagnostics (outer banks, fold-averaged)', '', '| pair | room % | share | FR² (OOF) | R² (OOF) | FR² (query) | R² (query) |', '|---|---|---|---|---|---|---|']
    for k, d in diag.items():
        md.append(f"| {k} | {d['room']:.3f} | {d['share']:.3f} | {d['fr2_oof']:.3f} | {d['r2_oof']:.3f} | {d['fr2_query']:.3f} | {d['r2_query']:.3f} |")
    md += ['', 'Split-half cos² at r*: ' + ', '.join(f"M->{y} {diag[f'M->{y}']['splithalf_cos2_at_rstar']:.3f}" for y in YS),
           'FR² under label-permuted G (mean): ' + ', '.join(f"M->{y} {diag[f'M->{y}']['fr2_oof_perm_mean']:.3f}" for y in YS), '']
    report['scenarios'][scen] = out

# ---------------------------------------------------------------- gates (PLAN section 6)
nc, ti = report['scenarios']['new_cell'], report['scenarios']['tissue']
g = {}
for y in YS:
    a = nc['Y'][y]['arms']['A1*']; b = ti['Y'][y]['arms']['A1*']
    g[f'GO-A1_newcell_{y}'] = bool(a['d_vs_H086'] >= .25 and a['wins_vs_H086'] >= 4)
    g[f'GO-A2_tissue_{y}'] = bool(b['d_vs_H086'] >= .15 and b['wins_vs_H086'] >= 4)
    bt = nc['Y'][y]['a1_beats_folds']
    g[f'GO-A3_controls_{y}'] = bool(bt['A3*'] >= 4 and bt['A4*mean'] >= 4 and bt['A5*mean'] >= 4)
    g[f'GO-A4_pairshuffle_{y}'] = bool(nc['Y'][y]['a7_over_a1_gain'] <= .5) if nc['Y'][y]['arms']['A1*']['d_vs_M'] > 0 else False
    g[f'PARTIAL_A2_within_0.05_{y}'] = bool(abs(nc['Y'][y]['a2_minus_a1']) < .05)
cells = [(s, k, d) for s in SCEN for k, d in report['scenarios'][s]['diag'].items() if d['room'] > .3]
if len(cells) >= 3:
    sh = [d['share'] for _, _, d in cells]
    g['G0a_spearman_FR2_share'] = float(spearmanr([d['fr2_oof'] for _, _, d in cells], sh).statistic)
    g['G0a_spearman_R2_share'] = float(spearmanr([d['r2_oof'] for _, _, d in cells], sh).statistic)
    g['G0a_n_cells'] = len(cells)
    g['G0a_pass'] = bool(g['G0a_spearman_FR2_share'] >= .5 and g['G0a_spearman_FR2_share'] > g['G0a_spearman_R2_share'])
else:
    g['G0a_n_cells'] = len(cells); g['G0a_pass'] = 'not evaluable (<3 cells with room > 0.3%)'
g['G0b_pass'] = bool(all(report['scenarios'][s]['diag']['M->RNA']['fr2_oof'] > report['scenarios'][s]['diag']['P->RNA']['fr2_oof'] for s in SCEN))
g['G0c_cos2'] = {f'{s}/{y}': report['scenarios'][s]['diag'][f'M->{y}']['splithalf_cos2_at_rstar'] for s in SCEN for y in YS}
g['G0c_pass'] = bool(all(v >= .5 for v in g['G0c_cos2'].values()))
newcell_any = any(g[f'GO-A1_newcell_{y}'] for y in YS)
full = {y: all(g[f'GO-A{i}_{k}_{y}'] for i, k in ((1, 'newcell'), (2, 'tissue'), (3, 'controls'), (4, 'pairshuffle'))) for y in YS}
g['GO-A_drug_full_by_Y'] = full
g['verdict_drug'] = ('NO-GO-A' if not newcell_any else
                     'GO-A (drug; CRISPR condition pending A9)' if any(full.values()) else 'MIXED (new-cell condition met for some Y; other GO-A conditions not all met)')
if newcell_any and any(g[f'PARTIAL_A2_within_0.05_{y}'] for y in YS if g[f'GO-A1_newcell_{y}']):
    g['verdict_drug'] += '; PARTIAL flag: A2 within 0.05 pp of A1 -> report as pipeline fix'
report['gates'] = g
json.dump(report, open(f'{OUT}/analysis.json', 'w'), indent=1)
md += ['## Gates', '', '```', json.dumps(g, indent=1), '```']
open(f'{OUT}/RESULT_AUTO.md', 'w').write('\n'.join(md) + '\n')
print(json.dumps(g, indent=1))
