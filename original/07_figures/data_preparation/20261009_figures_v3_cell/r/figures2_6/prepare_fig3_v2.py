"""Figure 3 (V2, 2026-10-09): functional utility of virtual layers.

Replays the frozen out-of-fold predictions of the crosslayer-matrix run
(both scenarios, five tissue-disjoint folds) into tidy plot tables.
Arms: M (direct, 'M only'), M+vRNA / M+vP (deployable: only M measured at
deployment, virtual layer generated by cross-fitted KRR), M+RNA / M+P
(measured-layer information references, NOT deployable), null_drug
(per-drug training mean).  No training, no p-values, no outcome-driven
example selection: examples are chosen by observed AUC coverage only.
"""
import csv, json, hashlib, warnings
from pathlib import Path
import numpy as np

RUN = Path('/public/home/mengxl/creed-research-runs/crosslayer-matrix-20261009-0001')
SRC = Path('/public/home/mengxl/creed-research-runs/gdsc-metabolite-full-protein-20260908-0001/output/result/source-inputs.npz')
ANN = Path('/public/home/mengxl/workspaces/creed-research/figure_work/20261009_figures2_6_v2/data/raw/figure2_6_extra/drug_annotations.json')
V2 = Path('/public/home/mengxl/workspaces/creed-research/figure_work/20261009_figures2_6_v2')
OUT = V2 / 'delivery_R_20261009/figures2_6/figure3/plot_data'
OUT.mkdir(parents=True, exist_ok=True)

SOURCES = {}
def reg(p):
    p = Path(p); SOURCES[str(p)] = hashlib.sha256(p.read_bytes()).hexdigest(); return p
def load(p):
    return np.load(reg(p), allow_pickle=False)
def save(name, rows):
    rows = list(rows); assert rows, name
    with (OUT / f'{name}.csv').open('w', newline='') as h:
        w = csv.DictWriter(h, fieldnames=list(rows[0])); w.writeheader()
        for r in rows:
            w.writerow({k: ('' if isinstance(v, (float, np.floating)) and not np.isfinite(v) else v) for k, v in r.items()})
    print('wrote', name, len(rows), flush=True)

SCEN = {'new_cell': 'New cell', 'tissue': 'Whole tissue'}
ARMS = ['M', 'M+vRNA', 'M+vP', 'M+RNA', 'M+P', 'null_drug']
VIRTUAL = {'M+vRNA': 'M+RNA', 'M+vP': 'M+P'}          # virtual arm -> paired measured reference
RANK_ARMS = ['M', 'M+vRNA', 'M+vP', 'M+RNA', 'M+P', 'null_drug']
CAL_ARMS = ['M', 'M+vRNA', 'M+vP', 'M+RNA', 'M+P']

src = load(SRC)
ids, tissues, auc = src['sample_ids'], src['tissues'], src['auc']
all_drugs = src['drug_ids'].astype(str)
assert len(set(ids)) == 421
annot = json.loads(reg(ANN).read_text())
name = lambda d: annot.get(str(d), {}).get('names', [str(d)])[0]

# stored metrics of the run, used only as replay checks
stored_fold, stored_drug = {}, {}
for sc in SCEN:
    with reg(RUN / f'output/{sc}/fold_metrics.csv').open() as h:
        for r in csv.DictReader(h): stored_fold[sc, int(r['fold']), r['arm']] = float(r['score'])
    with reg(RUN / f'output/{sc}/per_drug_metrics.csv').open() as h:
        for r in csv.DictReader(h): stored_drug[sc, int(r['fold']), r['arm'], r['drug_id']] = float(r['standardized_mse'])

fmetrics, drugs, samples, rankrows, cal = [], [], [], [], []
scores, smse, nobs, evaluated_sets, fold_cache = {}, {}, {}, {}, {}
checks = dict(fold_score_replays=0, per_drug_replays=0, max_abs_fold_diff=0.0, max_abs_drug_diff=0.0)
counts_all = {d: int(np.isfinite(auc[:, j]).sum()) for j, d in enumerate(all_drugs)}   # coverage over all 421 cells

for sc in SCEN:
    for f in range(5):
        z = load(RUN / f'output/{sc}/fold-{f}_predictions.npz')
        truth, sd, ev, panel, held, dids = z['truth'], z['train_sd'], z['evaluated'], z['panel'], z['held'], z['drug_ids'].astype(str)
        ref = auc[np.ix_(held, panel)]
        assert np.array_equal(np.isfinite(truth), np.isfinite(ref)) and np.allclose(np.nan_to_num(truth), np.nan_to_num(ref))
        assert np.array_equal(dids, all_drugs[panel])
        count = np.isfinite(truth).sum(axis=0)
        assert np.array_equal(ev, count >= 5), 'evaluated rule'
        evaluated_sets[sc, f] = set(dids[ev])
        fold_cache[sc, f] = dict(truth=truth, ev=ev, dids=dids, held=held, preds={a: z['pred__' + a] for a in ARMS})
        for a in ARMS:
            pred = z['pred__' + a]; assert np.isfinite(pred).all()
            with warnings.catch_warnings():
                warnings.simplefilter('ignore')
                err = ((pred - truth) / sd) ** 2; dm = np.nanmean(err, axis=0)
            score = float(np.sqrt(dm[ev].mean()))
            d = abs(score - stored_fold[sc, f, a]); checks['max_abs_fold_diff'] = max(checks['max_abs_fold_diff'], d)
            assert d < 1e-9, (sc, f, a, score, stored_fold[sc, f, a]); checks['fold_score_replays'] += 1
            scores[sc, f, a] = score
            fmetrics.append(dict(scenario=sc, fold=f, arm=a, srmse=score, drugs=int(ev.sum()), held_cells=len(held), observed_pairs=int(count[ev].sum())))
            for j, did in enumerate(dids):
                if ev[j]:
                    d2 = abs(dm[j] - stored_drug[sc, f, a, did]); checks['max_abs_drug_diff'] = max(checks['max_abs_drug_diff'], d2)
                    assert d2 < 1e-9; checks['per_drug_replays'] += 1
                    smse[sc, f, a, did] = float(dm[j]); nobs[sc, f, did] = int(count[j])
                    drugs.append(dict(scenario=sc, fold=f, arm=a, drug_id=did, name=name(did), n=int(count[j]), smse=float(dm[j])))
            for i, si in enumerate(held):
                ok = np.isfinite(truth[i, ev])
                samples.append(dict(scenario=sc, fold=f, arm=a, sample_id=ids[si], tissue=tissues[si],
                                    smse=float(np.nanmean(err[i, ev])) if ok.any() else np.nan, n=int(ok.sum())))
            if a in RANK_ARMS:   # retrospective top-k recall on the observed candidate pool of each cell line
                for i, si in enumerate(held):
                    okj = np.where(np.isfinite(truth[i]) & ev)[0]
                    order_true = okj[np.argsort(truth[i, okj], kind='stable')]; order_pred = okj[np.argsort(pred[i, okj], kind='stable')]
                    for k in [5, 10, 20, 50]:
                        if len(okj) >= k:
                            rankrows.append(dict(scenario=sc, fold=f, sample_id=ids[si], arm=a, k=k,
                                                 recall=len(set(order_true[:k]) & set(order_pred[:k])) / k, candidates=len(okj)))
print('replay checks', checks, flush=True)

# Example drugs: evaluated in every fold of both scenarios; ordered by observed AUC coverage, ties by numeric ID.
common_both = set.intersection(*evaluated_sets.values())
examples = sorted(common_both, key=lambda d: (-counts_all[d], int(d)))[:20]
save('drug_selection', [dict(drug_id=d, name=name(d), observed=counts_all[d], rank=i + 1) for i, d in enumerate(examples)])

# Observed-AUC-binned diagnostics for the six most covered example drugs (five bins per fold, pooled later by bin size).
for sc in SCEN:
    for f in range(5):
        c = fold_cache[sc, f]; truth, dids = c['truth'], c['dids']
        for j, did in enumerate(dids):
            if did in examples[:6]:
                good = np.where(np.isfinite(truth[:, j]))[0]; ordered = good[np.argsort(truth[good, j], kind='stable')]
                for b, block in enumerate(np.array_split(ordered, 5)):
                    if len(block):
                        for a in CAL_ARMS:
                            cal.append(dict(scenario=sc, drug_id=did, name=name(did), fold=f, bin=b + 1, n=len(block), arm=a,
                                            observed_auc=float(truth[block, j].mean()), predicted_auc=float(c['preds'][a][block, j].mean())))
save('fold_metrics', fmetrics); save('per_drug_metrics', drugs); save('per_sample_metrics', samples)
save('ranking_recall', rankrows); save('calibration_bins', cal)

# Paired per-drug deltas vs the direct M-only head (positive = the arm has lower error than M only).
deltas = []
for (sc, f, a, did), v in smse.items():
    if a != 'M':
        deltas.append(dict(scenario=sc, fold=f, drug_id=did, name=name(did), arm=a, delta=smse[sc, f, 'M', did] - v, n=nobs[sc, f, did]))
save('drug_deltas', deltas)

# Per-drug RMSE over folds for drugs evaluated in all five folds of a scenario (panel D).
common_sc = {sc: sorted(set.intersection(*[evaluated_sets[sc, f] for f in range(5)]), key=int) for sc in SCEN}
rmse_rows = []
for sc in SCEN:
    for d in common_sc[sc]:
        for a in ARMS:
            rmse_rows.append(dict(scenario=sc, drug_id=d, name=name(d), arm=a, rmse=float(np.sqrt(np.mean([smse[sc, f, a, d] for f in range(5)])))))
save('drug_rmse', rmse_rows)

# Recovery fraction per fold: (direct - virtual) / (direct - measured), each virtual layer against its own measured reference.
head = []
for sc in SCEN:
    for f in range(5):
        for va, ma in VIRTUAL.items():
            d0, dv, dm_ = scores[sc, f, 'M'], scores[sc, f, va], scores[sc, f, ma]
            assert d0 - dm_ > 0
            head.append(dict(scenario=sc, fold=f, virtual_arm=va, measured_arm=ma, direct=d0, virtual=dv, measured=dm_, null=scores[sc, f, 'null_drug'],
                             recovered=d0 - dv, headroom=d0 - dm_, recovered_fraction=(d0 - dv) / (d0 - dm_)))
save('headroom', head)

# Wins per fold (panel H).
wins = []
for sc in SCEN:
    for f in range(5):
        for a in ['M+vRNA', 'M+vP', 'M+RNA', 'M+P']:
            dd = [x for x in deltas if x['scenario'] == sc and x['fold'] == f and x['arm'] == a]
            wins.append(dict(scenario=sc, fold=f, arm=a, total=len(dd), lower=sum(x['delta'] > 0 for x in dd), fraction=sum(x['delta'] > 0 for x in dd) / len(dd)))
save('drug_wins', wins)

# Protocol numbers for the schematic and caption.
proto = dict(cell_lines=421, folds=5, scenarios={}, arms=ARMS,
             mean_srmse={sc: {a: float(np.mean([scores[sc, f, a] for f in range(5)])) for a in ARMS} for sc in SCEN},
             mean_recovered_fraction={sc: {va: float(np.mean([h['recovered_fraction'] for h in head if h['scenario'] == sc and h['virtual_arm'] == va])) for va in VIRTUAL} for sc in SCEN},
             mean_gain_pct={sc: {a: float(100 * (1 - np.mean([scores[sc, f, a] for f in range(5)]) / np.mean([scores[sc, f, 'M'] for f in range(5)]))) for a in ARMS} for sc in SCEN},
             wins={sc: {a: [f"{w['lower']}/{w['total']}" for w in wins if w['scenario'] == sc and w['arm'] == a] for a in ['M+vRNA', 'M+vP', 'M+RNA', 'M+P']} for sc in SCEN},
             example_drugs=[dict(drug_id=d, name=name(d), observed=counts_all[d]) for d in examples],
             common_drugs_all_folds={sc: len(common_sc[sc]) for sc in SCEN}, example_pool=len(common_both))
for sc in SCEN:
    dr = [r['drugs'] for r in fmetrics if r['scenario'] == sc and r['arm'] == 'M']; hc = [r['held_cells'] for r in fmetrics if r['scenario'] == sc and r['arm'] == 'M']
    proto['scenarios'][sc] = dict(label=SCEN[sc], minimum_drugs=min(dr), maximum_drugs=max(dr), min_held=min(hc), max_held=max(hc))
(OUT / 'protocol.json').write_text(json.dumps(proto, indent=1))

lines = ['# Figure 3 V2 data sources', '', f'Generated by `{Path(__file__).name}` (sha256 `{hashlib.sha256(Path(__file__).read_bytes()).hexdigest()}`).', '',
         'Replay checks: ' + json.dumps(checks), '', '| input | sha256 |', '|---|---|'] + [f'| `{p}` | `{s}` |' for p, s in sorted(SOURCES.items())]
lines += ['', 'Outputs: ' + ', '.join(sorted(p.name for p in OUT.iterdir())), '',
          'Arms: M = direct metabolite head (M only); M+vRNA / M+vP = M only at deployment, virtual RNA / virtual protein layer generated by cross-fitted KRR from M (deployable); M+RNA / M+P = measured layer added (information reference, not deployable); null_drug = per-drug training mean.',
          'Example drugs: evaluated in all 5 folds of both scenarios, ordered by observed AUC coverage over the 421 cell lines, ties by numeric drug ID; no outcome-driven selection.']
(OUT / 'FIG3_DATA_SOURCES.md').write_text('\n'.join(lines) + '\n')
print(json.dumps({k: proto[k] for k in ['mean_srmse', 'mean_recovered_fraction', 'mean_gain_pct', 'wins', 'common_drugs_all_folds', 'example_pool', 'scenarios']}, indent=1))
